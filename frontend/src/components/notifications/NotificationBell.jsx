import { useEffect, useRef, useState } from "react";
import {
  AlertTriangle,
  Bell,
  CheckCheck,
  CheckCircle2,
  Info,
  Trash2,
  XCircle,
} from "lucide-react";
import { useNotifications } from "../../context/NotificationContext";
import { formatRelativeTime } from "../../lib/formatters";

const ICONS = {
  success: { icon: CheckCircle2, className: "text-emerald-600 bg-emerald-50" },
  error: { icon: XCircle, className: "text-rose-600 bg-rose-50" },
  warning: { icon: AlertTriangle, className: "text-amber-600 bg-amber-50" },
  info: { icon: Info, className: "text-sky-600 bg-sky-50" },
};

export default function NotificationBell() {
  const { notifications, unreadCount, markAllRead, clearAll } = useNotifications();
  const [open, setOpen] = useState(false);
  const containerRef = useRef(null);

  useEffect(() => {
    if (!open) return undefined;

    function handlePointerDown(event) {
      if (!containerRef.current?.contains(event.target)) {
        setOpen(false);
      }
    }
    function handleKeyDown(event) {
      if (event.key === "Escape") setOpen(false);
    }

    document.addEventListener("mousedown", handlePointerDown);
    document.addEventListener("keydown", handleKeyDown);
    return () => {
      document.removeEventListener("mousedown", handlePointerDown);
      document.removeEventListener("keydown", handleKeyDown);
    };
  }, [open]);

  function toggleOpen() {
    setOpen((current) => {
      const next = !current;
      if (next) markAllRead();
      return next;
    });
  }

  return (
    <div className="relative" ref={containerRef}>
      <button
        type="button"
        onClick={toggleOpen}
        className="relative flex h-9 w-9 items-center justify-center rounded-lg border border-slate-200 bg-white text-slate-500 shadow-sm transition hover:border-slate-300 hover:text-slate-700"
        aria-label={`Notifications${unreadCount ? `, ${unreadCount} unread` : ""}`}
        aria-haspopup="true"
        aria-expanded={open}
      >
        <Bell size={17} />
        {unreadCount > 0 && (
          <span className="absolute -right-1 -top-1 flex h-4 min-w-4 items-center justify-center rounded-full bg-forest-700 px-1 text-[10px] font-semibold text-white">
            {unreadCount > 9 ? "9+" : unreadCount}
          </span>
        )}
      </button>

      {open && (
        <div className="absolute right-0 z-40 mt-2 w-[min(22rem,calc(100vw-2rem))] overflow-hidden rounded-xl border border-slate-200 bg-white shadow-dropdown">
          <div className="flex items-center justify-between border-b border-slate-100 px-4 py-3">
            <div>
              <p className="text-sm font-semibold text-slate-900">Notifications</p>
              <p className="text-[11px] text-slate-500">
                Generated by real session and system events
              </p>
            </div>
            {notifications.length > 0 && (
              <button
                type="button"
                onClick={clearAll}
                className="inline-flex items-center gap-1 rounded-md px-2 py-1 text-[11px] font-medium text-slate-500 transition hover:bg-slate-100 hover:text-slate-700"
              >
                <Trash2 size={12} />
                Clear
              </button>
            )}
          </div>

          <div className="max-h-80 overflow-y-auto scrollbar-thin">
            {notifications.length === 0 ? (
              <div className="px-4 py-10 text-center">
                <span className="mx-auto flex h-10 w-10 items-center justify-center rounded-full bg-slate-100 text-slate-400">
                  <Bell size={18} />
                </span>
                <p className="mt-3 text-sm font-medium text-slate-700">No notifications</p>
                <p className="mt-1 text-xs text-slate-500">
                  Sign-in, health changes and settings updates appear here.
                </p>
              </div>
            ) : (
              <ul className="divide-y divide-slate-100">
                {notifications.map((item) => {
                  const meta = ICONS[item.type] || ICONS.info;
                  const Icon = meta.icon;
                  return (
                    <li key={item.id} className="flex items-start gap-3 px-4 py-3">
                      <span
                        className={`mt-0.5 flex h-8 w-8 shrink-0 items-center justify-center rounded-lg ${meta.className}`}
                      >
                        <Icon size={15} />
                      </span>
                      <div className="min-w-0 flex-1">
                        <div className="flex items-start justify-between gap-2">
                          <p className="text-xs font-semibold text-slate-900">
                            {item.title}
                          </p>
                          <span className="shrink-0 text-[10px] text-slate-400">
                            {formatRelativeTime(item.createdAt)}
                          </span>
                        </div>
                        {item.message && (
                          <p className="mt-0.5 text-[11px] leading-5 text-slate-600">
                            {item.message}
                          </p>
                        )}
                        <p className="mt-1 text-[10px] font-medium uppercase tracking-[0.1em] text-slate-400">
                          {item.source}
                        </p>
                      </div>
                    </li>
                  );
                })}
              </ul>
            )}
          </div>

          {notifications.length > 0 && (
            <div className="flex items-center justify-between border-t border-slate-100 bg-slate-50 px-4 py-2">
              <span className="inline-flex items-center gap-1.5 text-[11px] text-slate-500">
                <CheckCheck size={12} />
                All marked as read
              </span>
              <span className="text-[11px] text-slate-400">
                {notifications.length} saved
              </span>
            </div>
          )}
        </div>
      )}
    </div>
  );
}
